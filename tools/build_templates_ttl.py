"""Generate ontology/templates.ttl: the template catalogue as RDF with PROV-O provenance (issue #95, epic #89).

    python tools/build_templates_ttl.py           rewrite ontology/templates.ttl
    python tools/build_templates_ttl.py --check   exit 1 if templates.ttl is out of date (CI)

Reads ldraw_tools/data/templates/*.json (leaves stay JSON: the app consumes them). Needs no rdflib to write; checking the result
against ontology/templates-shapes.ttl needs rdflib and pyshacl (toolkit-only, see tests/test_templates_ttl.py).
Mapping: a template is an obd:Template (a prov:Entity) in tpl:<id>; it prov:wasDerivedFrom its source model (an obd:SourceModel in
src:<file>) and prov:wasAttributedTo the author (agent:<slug>); dcterms:license goes on the source and, with the same IRI, on the
template. families/kinds -> obd:family/obd:kind; roles -> obd:carriesRole (concepts of ontology/roles.ttl); every offered parameter that is
not a role colour (size, swap, include) and every role colour -> an obd:Knob in tpl:<id>/knob/<key>.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TTL = ROOT / 'ontology' / 'templates.ttl'
TEMPLATES = ROOT / 'ldraw_tools' / 'data' / 'templates'
BASE = 'https://alessionar.github.io/open-brick-designer/ns/'
LICENCES = {'CCAL version 2.0': 'https://creativecommons.org/licenses/by/2.0/'}

HEADER = f'''# Reference builds as RDF (issue #95, epic #89; design: docs/plans/active/build-ontology/PROPOSAL.md).
# GENERATED by tools/build_templates_ttl.py from ldraw_tools/data/templates/*.json, do not edit; CI fails on a diff.
# A template is an instance of obd:Template: roles, knobs and PROV-O provenance (source model, author, licence). The licence of a
# template is that of its source model (CCAL 2.0); the ontology files themselves are CC BY-SA 4.0. Query it with SPARQL, e.g. the
# templates that carry a roof role: SELECT ?t WHERE {{ ?t a obd:Template ; obd:carriesRole role:roof }}.
@prefix agent: <{BASE}agent/> .
@prefix dcterms: <http://purl.org/dc/terms/> .
@prefix obd: <{BASE}obd#> .
@prefix owl: <http://www.w3.org/2002/07/owl#> .
@prefix prov: <http://www.w3.org/ns/prov#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix role: <{BASE}role/> .
@prefix skos: <http://www.w3.org/2004/02/skos/core#> .
@prefix src: <{BASE}source/> .
@prefix tpl: <{BASE}template/> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .

<{BASE}template/> a owl:Ontology ;
    dcterms:title "Open Brick Designer reference builds"@en ;
    dcterms:license <https://creativecommons.org/licenses/by-sa/4.0/> ;
    owl:imports <{BASE}obd>, <{BASE}role/> .

obd:Template a owl:Class ; rdfs:subClassOf prov:Entity ; rdfs:label "Template"@en ;
    rdfs:comment "A reference build derived from a source model: its roles, the knobs it offers and where it came from."@en .
obd:SourceModel a owl:Class ; rdfs:subClassOf prov:Entity ; rdfs:label "Source model"@en ;
    rdfs:comment "The model file a template was derived from."@en .
obd:Knob a owl:Class ; rdfs:label "Knob"@en ; rdfs:comment "One adjustable parameter of a template."@en .
obd:SizeKnob a owl:Class ; rdfs:subClassOf obd:Knob ; rdfs:label "Size knob"@en ; rdfs:comment "Studs or courses added or removed along an axis."@en .
obd:SwapKnob a owl:Class ; rdfs:subClassOf obd:Knob ; rdfs:label "Swap knob"@en ; rdfs:comment "Replaces every part of one kind by an equivalent part."@en .
obd:IncludeKnob a owl:Class ; rdfs:subClassOf obd:Knob ; rdfs:label "Include knob"@en ; rdfs:comment "Keeps or drops a sub-assembly."@en .
obd:ColourKnob a owl:Class ; rdfs:subClassOf obd:Knob ; rdfs:label "Colour knob"@en ; rdfs:comment "Colour of every placement that carries a role."@en .

obd:family a owl:DatatypeProperty ; rdfs:domain obd:Template ; rdfs:range xsd:string ; rdfs:comment "Family word the template is filed under (house, truck, train)."@en .
obd:kind a owl:DatatypeProperty ; rdfs:domain obd:Template ; rdfs:range xsd:string ; rdfs:comment "Phrase the fast path matches a request against."@en .
obd:carriesRole a owl:ObjectProperty ; rdfs:domain obd:Template ; rdfs:range skos:Concept ; rdfs:comment "A role (concept of the role scheme) some placement of the template carries."@en .
obd:hasKnob a owl:ObjectProperty ; rdfs:domain obd:Template ; rdfs:range obd:Knob .
obd:forRole a owl:ObjectProperty ; rdfs:domain obd:ColourKnob ; rdfs:comment "The role a colour knob colours."@en .
obd:legoSet a owl:DatatypeProperty ; rdfs:domain obd:SourceModel ; rdfs:range xsd:string ; rdfs:comment "Number of the LEGO set the source model builds, when it has one."@en .
obd:partCount a owl:DatatypeProperty ; rdfs:domain obd:Template ; rdfs:range xsd:integer ; rdfs:comment "Parts in the template as derived."@en .
'''

KNOB_CLASS = (('colour_', 'ColourKnob'), ('swap_', 'SwapKnob'), ('include_', 'IncludeKnob'))


def lit(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def slug(text):
    return re.sub(r'[^a-z0-9]+', '-', re.sub(r'\[.*?\]', '', text.lower())).strip('-')


def role_name(role):
    """Role local name in roles.ttl: a per-colour sub-role is `wall:stripe-a` there and `wall_stripe_a` in a template (issue #220)."""
    return re.sub(r'_stripe_([a-z])$', r':stripe-\1', role)


def knob_class(key):
    for prefix, cls in KNOB_CLASS:
        if key.startswith(prefix):
            return cls
    return 'SizeKnob'


def licence(source):
    text = source.get('license', '')
    for name, iri in LICENCES.items():
        if name in text:
            return iri
    return None


def template_block(data):
    tid, source = data['id'], data['source']
    iri_lic = licence(source)
    author = source.get('author')
    agent = f"agent:{slug(author)}" if author else None
    srcname = source['name']
    lines = []
    if agent:
        lines.append(f'{agent} a prov:Agent ; rdfs:label {lit(author)} .')
    sm = [f'src:{srcname} a obd:SourceModel, prov:Entity', f'    dcterms:title {lit(srcname)}']
    num = re.match(r'(\d+)-\d+_', srcname)
    if num:
        sm.append(f'    obd:legoSet {lit(num.group(1))}')
    if agent:
        sm.append(f'    prov:wasAttributedTo {agent}')
    if iri_lic:
        sm.append(f'    dcterms:license <{iri_lic}>')
    lines.append(' ;\n'.join(sm) + ' .')
    t = [f'tpl:{tid} a obd:Template, prov:Entity',
         f'    dcterms:title {lit(data["title"])}@en',
         f'    dcterms:description {lit(data["description"])}@en',
         f'    dcterms:identifier {lit(tid)}',
         f'    prov:wasDerivedFrom src:{srcname}']
    if agent:
        t.append(f'    prov:wasAttributedTo {agent}')
    if iri_lic:
        t.append(f'    dcterms:license <{iri_lic}>')
    t.append('    obd:family ' + ', '.join(lit(f) for f in data['families']))
    t.append('    obd:kind ' + ', '.join(lit(k) for k in data['kinds']))
    t.append('    obd:carriesRole ' + ', '.join(f'role:{role_name(r)}' for r in sorted(data['roles'])))
    t.append(f'    obd:partCount {len(data["leaves"])}')
    knobs = list(data['params'])
    t.append('    obd:hasKnob ' + ', '.join(f'<{BASE}template/{tid}/knob/{k}>' for k in knobs))
    lines.append(' ;\n'.join(t) + ' .')
    for key, spec in data['params'].items():
        k = [f'<{BASE}template/{tid}/knob/{key}> a obd:{knob_class(key)}',
             f'    dcterms:identifier {lit(key)}',
             f'    rdfs:comment {lit(spec["description"])}@en']
        if key.startswith('colour_'):
            k.append(f'    obd:forRole role:{role_name(key[len("colour_"):])}')
        default = spec.get('default')
        if isinstance(default, bool):
            k.append(f'    obd:default {str(default).lower()}')
        elif isinstance(default, int):
            k.append(f'    obd:default {default}')
        elif default is not None:
            k.append(f'    obd:default {lit(str(default))}')
        lines.append(' ;\n'.join(k) + ' .')
    return '\n\n'.join(lines)


def render():
    blocks = [template_block(json.loads(p.read_text(encoding='utf-8'))) for p in sorted(TEMPLATES.glob('*.json'))]
    # one agent or source can serve several templates: keep the first definition of each subject
    seen, out = set(), []
    for block in blocks:
        for para in block.split('\n\n'):
            subject = para.split(' ', 1)[0]
            if subject not in seen:
                seen.add(subject)
                out.append(para)
    return HEADER + '\n' + '\n\n'.join(out) + '\n'


def main(argv):
    text = render()
    if '--check' in argv:
        if not TTL.exists() or TTL.read_text(encoding='utf-8') != text:
            print('ontology/templates.ttl is out of date: run python tools/build_templates_ttl.py')
            return 1
        return 0
    TTL.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
